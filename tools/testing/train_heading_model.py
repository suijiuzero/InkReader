"""Train a reproducible, numeric-only logistic heading model using JVM-exported features.

No third-party Python packages required. Export with INK_MODEL_EXPORT=<absolute.tsv>
and :app:unitTest first. Holdout rows NEVER enter fitting or threshold selection.
"""
import argparse
import csv
import hashlib
import json
import math
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / 'tools/testing/heading-model-v1.json'
GENERATED = ROOT / 'app/src/main/java/com/inkreader/parse/HeadingModelWeights.kt'


def sigmoid(value):
    value = max(-40, min(40, value))
    return 1 / (1 + math.exp(-value))


def read(path):
    with path.open(encoding='utf-8') as source:
        reader = csv.DictReader(source, delimiter='\t')
        names = reader.fieldnames[6:]
        rows = []
        for raw in reader:
            assert raw['partition'] in ('development', 'holdout'), 'Unknown data partition'
            group = raw['group'] if '/' in raw['group'] else raw['dataset'] + '/' + raw['group']
            split = 'holdout' if raw['partition'] == 'holdout' else (
                'validation' if int(hashlib.sha256(group.encode()).hexdigest()[:8], 16) % 5 == 0 else 'train')
            line = int(raw['line']); label = int(raw['label']); vector = [float(raw[n]) for n in names]
            assert line >= 0 and (label >= 0 if line == 0 else label in (0,1)), 'Invalid supervised label'
            assert vector and all(math.isfinite(x) and 0 <= x <= 1 for x in vector), 'Invalid feature values'
            rows.append(dict(group=group, case=raw['dataset'] + '/' + raw['case'], split=split,
                             line=line, y=label, x=vector))
    for group in {row['group'] for row in rows}:
        partitions = {row['split'] == 'holdout' for row in rows if row['group'] == group}
        assert len(partitions) == 1, f'Work leaks across development/holdout: {group}'
    return names, rows


def metrics(rows, coefficients, threshold):
    tp = fp = fn = 0
    for row in rows:
        if row['line'] == 0:
            continue
        yes = sigmoid(coefficients[0] + sum(w*x for w, x in zip(coefficients[1:], row['x']))) >= threshold
        tp += bool(yes and row['y']); fp += bool(yes and not row['y']); fn += bool(not yes and row['y'])
    # Include headings outside the candidate length budget in recall, not just easy candidates.
    total = sum(r['y'] for r in rows if r['line'] == 0)
    if total:
        fn = total - tp
    return dict(TP=tp, FP=fp, FN=fn, precision=tp/max(1, tp+fp), recall=tp/max(1, tp+fn),
                f05=1.25*tp/max(1, 1.25*tp+fp+0.25*fn))


def train(names, rows):
    training = [r for r in rows if r['split'] == 'train' and r['line'] > 0]
    validation = [r for r in rows if r['split'] == 'validation']
    assert training and validation
    assert {r['y'] for r in training} == {0, 1}
    counts = Counter((r['group'], r['y']) for r in training)
    sample_weights = [1 / counts[r['group'], r['y']] for r in training]
    total = sum(sample_weights)
    weights = [0.0] * (len(names)+1)
    # Fixed full-batch optimizer; hyperparameters declared before inspecting holdout.
    for _ in range(1200):
        gradient = [0.0] * len(weights)
        for r, sample_weight in zip(training, sample_weights):
            error = (sigmoid(weights[0] + sum(w*x for w, x in zip(weights[1:], r['x']))) - r['y']) * sample_weight / total
            gradient[0] += error
            for i, x in enumerate(r['x'], 1):
                gradient[i] += error*x
        for i in range(len(weights)):
            weights[i] -= 0.8 * (gradient[i] + (0.002*weights[i] if i else 0))
    # Avoid insignificant platform-libm differences changing the committed artifact.
    weights = [round(w, 10) for w in weights]
    candidates = [(t/100, metrics(validation, weights, t/100)) for t in range(50, 100)]
    threshold, score = max(candidates, key=lambda item: (item[1]['f05'], item[1]['precision'], item[0]))
    result = dict(version='ink-heading-lr-v1', features=names, coefficients=weights, threshold=threshold,
                  optimizer=dict(epochs=1200, learningRate=0.8, l2=0.002, classAndWorkBalanced=True),
                  thresholdSelection='max validation F0.5, ties precision then higher threshold',
                  validation=score)
    return result


def kotlin(model):
    return ('// Generated by tools/testing/train_heading_model.py. Do not edit weights manually.\n'
            'package com.inkreader.parse\n\ninternal object HeadingModelWeights {\n'
            f'    const val version = "{model["version"]}"\n'
            f'    const val fingerprint = "{model["fingerprint"]}"\n'
            f'    const val threshold = {model["threshold"]}\n'
            '    val features = listOf(' + ', '.join(json.dumps(n) for n in model['features']) + ')\n'
            '    val coefficients = doubleArrayOf(' + ', '.join(repr(w) for w in model['coefficients']) + ')\n}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('features', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    from verify_frozen_fixtures import verify
    verify(ROOT / 'tests/fixtures')
    extra = ROOT / 'tests/fixtures/heading-training-extra'
    if extra.exists():
        hashes = json.loads((extra/'reviewed-sha256.json').read_text('utf-8'))
        for name, expected in hashes.items():
            path = extra/name
            assert path.parent == extra and hashlib.sha256(path.read_bytes()).hexdigest()==expected, f'Reviewed sample changed: {name}'
    names, rows = read(args.features)
    model = train(names, rows)
    model['groups'] = {split: sorted({r['group'] for r in rows if r['split'] == split}) for split in ['train', 'validation', 'holdout']}
    assert not (set(model['groups']['train']) & set(model['groups']['validation']))
    assert not ((set(model['groups']['train']) | set(model['groups']['validation'])) & set(model['groups']['holdout']))
    model['fitInputSha256'] = hashlib.sha256(json.dumps([r for r in rows if r['split'] != 'holdout'], sort_keys=True).encode()).hexdigest()
    model['fingerprint'] = hashlib.sha256(json.dumps(model, sort_keys=True).encode()).hexdigest()
    # Evaluation occurs only after weights and threshold are fixed.
    report = {split: metrics([r for r in rows if r['split'] == split], model['coefficients'], model['threshold']) for split in model['groups']}
    report['counts'] = {split: dict(groups=len(model['groups'][split]), cases=len({r['case'] for r in rows if r['split']==split}),
                                  candidates=sum(r['split']==split and r['line']>0 for r in rows)) for split in model['groups']}
    payload = json.dumps(model, ensure_ascii=False, indent=2) + '\n'
    generated = kotlin(model)
    if args.check:
        assert MODEL.read_text('utf-8') == payload, 'Trained artifact is stale'
        assert GENERATED.read_text('utf-8') == generated, 'Android artifact is stale'
    else:
        MODEL.write_text(payload, encoding='utf-8')
        GENERATED.write_text(generated, encoding='utf-8')
    output = ROOT / 'app/build/audit/heading-model-evaluation.json'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
